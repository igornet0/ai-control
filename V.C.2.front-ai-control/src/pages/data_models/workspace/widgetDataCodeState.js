/**
 * Shared DataCode state helpers for widget editors.
 */
import { dataModelService } from '../../../services/dataModelService';
import { parseDbWidgetId } from './widgetDbSync.js';
import { widgetHasDataCode, widgetIdKey, tabNameForWidget } from './widgetGraphOrder.js';
import {
  buildDataCodeEditorTabs,
  extractSavedTabContent,
  pruneEditorSessionPayload,
} from './buildDataCodeEditorTabs.js';
import {
  resolveWidgetDataCodeContent,
  widgetCodeStoragePayload,
} from './resolveWidgetDataCode.js';

async function fetchSavedEditorSession(modelId) {
  if (!modelId) return null;
  try {
    const response = await dataModelService.getModelCode(modelId);
    return response?.code_data || null;
  } catch {
    return null;
  }
}

export async function fetchSavedCodeMap(modelId, widgets = []) {
  const savedCodeByWidgetId = {};
  if (!modelId) return savedCodeByWidgetId;

  await Promise.all(
    widgets.filter(widgetHasDataCode).map(async (widget) => {
      const id = parseDbWidgetId(widget);
      if (!id) return;
      try {
        const codeResponse = await dataModelService.getModelCode(modelId, id);
        savedCodeByWidgetId[widgetIdKey(id)] = extractSavedTabContent(codeResponse);
      } catch {
        savedCodeByWidgetId[widgetIdKey(id)] = '';
      }
    }),
  );

  return savedCodeByWidgetId;
}

/**
 * Widgets whose DataCode is not yet stored in data_model_widget_code.
 * Compile/preview read only that table — settings on the canvas are not enough.
 */
export function planMissingWidgetDataCodeSaves(
  widgets = [],
  savedCodeByWidgetId = {},
  widgetManager = null,
) {
  const plans = [];
  for (const widget of (widgets || []).filter(widgetHasDataCode)) {
    const widgetId = parseDbWidgetId(widget);
    if (!widgetId) continue;
    const saved = String(savedCodeByWidgetId[widgetIdKey(widgetId)] || '').trim();
    if (saved) continue;
    const content = getAutoGeneratedWidgetCode(widget, widgetManager);
    if (!String(content || '').trim()) continue;
    plans.push({
      widgetId,
      content,
      name: tabNameForWidget(widget),
    });
  }
  return plans;
}

/**
 * Persist auto-generated DataCode for widgets that have none saved yet.
 * Does not overwrite user-edited (or previously saved) code.
 */
export async function persistMissingWidgetDataCode(
  modelId,
  widgets = [],
  widgetManager = null,
) {
  if (!modelId) return {};
  const savedCodeByWidgetId = await fetchSavedCodeMap(modelId, widgets);
  const plans = planMissingWidgetDataCodeSaves(widgets, savedCodeByWidgetId, widgetManager);
  if (!plans.length) return savedCodeByWidgetId;

  await Promise.all(
    plans.map(async (plan) => {
      await dataModelService.saveModelCode(
        modelId,
        widgetCodeStoragePayload({
          name: plan.name,
          content: plan.content,
          widgetId: plan.widgetId,
        }),
        false,
        plan.widgetId,
      );
      savedCodeByWidgetId[widgetIdKey(plan.widgetId)] = plan.content;
    }),
  );
  return savedCodeByWidgetId;
}

export function getAutoGeneratedWidgetCode(widget, widgetManager = null) {
  return resolveWidgetDataCodeContent(widget, '', widgetManager);
}

export function isWidgetCodeModified(widget, savedContent = '', widgetManager = null) {
  const saved = String(savedContent || '').trim();
  if (!saved) return false;
  const auto = getAutoGeneratedWidgetCode(widget, widgetManager).trim();
  return saved !== auto;
}

export async function checkWidgetCodeModified(modelId, widget, widgetManager = null) {
  if (!widget || !widgetHasDataCode(widget)) return false;
  const widgetId = parseDbWidgetId(widget);
  if (!modelId || !widgetId) return false;

  const savedMap = await fetchSavedCodeMap(modelId, [widget]);
  const saved = savedMap[widgetIdKey(widgetId)] || '';
  return isWidgetCodeModified(widget, saved, widgetManager);
}

export async function prepareDataCodeEditorSession({
  modelId,
  engineRef,
  selectedWidgetId = null,
  runtimeOverrides = null,
} = {}) {
  const widgetManager = engineRef?.current?.widgetManager;
  const widgets = widgetManager?.getAllWidgets?.() || [];
  const connections = engineRef?.current?.getAllConnections?.() || [];
  const [savedCodeByWidgetId, savedEditorSession] = await Promise.all([
    persistMissingWidgetDataCode(modelId, widgets, widgetManager),
    fetchSavedEditorSession(modelId),
  ]);

  if (runtimeOverrides && typeof runtimeOverrides === 'object') {
    for (const [key, value] of Object.entries(runtimeOverrides)) {
      if (typeof value === 'string') savedCodeByWidgetId[key] = value;
    }
  }

  return buildDataCodeEditorTabs({
    widgets,
    connections,
    savedCodeByWidgetId,
    widgetManager,
    selectedWidgetId,
    savedEditorSession,
  });
}

export async function regenerateWidgetDataCode(modelId, widget, widgetManager = null) {
  const widgetId = parseDbWidgetId(widget);
  const content = getAutoGeneratedWidgetCode(widget, widgetManager);
  if (modelId && widgetId) {
    await dataModelService.saveModelCode(
      modelId,
      widgetCodeStoragePayload({
        name: tabNameForWidget(widget),
        content,
        widgetId,
      }),
      false,
      widgetId,
    );
  }
  return content;
}

/**
 * Remove deleted canvas widgets from the saved Datacode editor session (tabs + dismissed).
 * Widget code rows are deleted with the widget on the backend; this keeps session tabs in sync.
 */
export async function pruneEditorSessionForDeletedWidgets(modelId, deletedWidgetIds = []) {
  if (!modelId || !deletedWidgetIds?.length) return null;
  const session = await fetchSavedEditorSession(modelId);
  const payload = pruneEditorSessionPayload(session, deletedWidgetIds);
  if (!payload) return null;
  await dataModelService.saveModelCode(modelId, payload, false);
  return payload;
}
